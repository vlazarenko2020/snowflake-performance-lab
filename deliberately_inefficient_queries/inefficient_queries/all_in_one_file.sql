-- 6. Six-table join plus several window functions with different PARTITION BYs, each one re-sorting ~673M rows
SELECT * FROM (
  SELECT f.FRANCHISE_ID, f.FIRST_NAME, t.TRUCK_ID, l.CITY, m.TRUCK_BRAND_NAME, d.PRICE,
         ROW_NUMBER() OVER (PARTITION BY f.FRANCHISE_ID ORDER BY d.PRICE DESC) rn,
         SUM(d.PRICE) OVER (PARTITION BY f.FRANCHISE_ID) franchise_rev,
         SUM(d.PRICE) OVER (PARTITION BY l.CITY) city_rev
  FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL d
  JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_HEADER h ON h.ORDER_ID = d.ORDER_ID
  JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.TRUCK t ON t.TRUCK_ID = h.TRUCK_ID
  JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.FRANCHISE f ON f.FRANCHISE_ID = t.FRANCHISE_ID
  JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.LOCATION l ON l.LOCATION_ID = h.LOCATION_ID
  JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.MENU m ON m.MENU_ITEM_ID = d.MENU_ITEM_ID
) WHERE rn = 1 ORDER BY franchise_rev DESC LIMIT 10;

-- 7. Join on a function-wrapped text column (UPPER(TRIM(city))) that can match many rows, then moving average + LAG over the whole history
WITH daily AS (
  SELECT h.TRUCK_ID, TO_DATE(h.ORDER_TS) dt, c.COUNTRY, SUM(d.PRICE) rev
  FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_HEADER h
  JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL d ON d.ORDER_ID = h.ORDER_ID
  JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.LOCATION l ON l.LOCATION_ID = h.LOCATION_ID
  JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.COUNTRY c ON UPPER(TRIM(c.CITY)) = UPPER(TRIM(l.CITY))
  GROUP BY 1,2,3
)
SELECT COUNTRY, MAX(moving_avg), MAX(rev - prev_rev)
FROM (
  SELECT *, AVG(rev) OVER (PARTITION BY TRUCK_ID ORDER BY dt ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) moving_avg,
         LAG(rev) OVER (PARTITION BY TRUCK_ID ORDER BY dt) prev_rev
  FROM daily
) GROUP BY COUNTRY ORDER BY 2 DESC LIMIT 10;

-- 8. IN-subquery with YEAR() on the filter column (no partition skipping), plus a correlated AVG subquery per item
SELECT m.ITEM_CATEGORY, COUNT(*) cnt
FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL d
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.MENU m ON m.MENU_ITEM_ID = d.MENU_ITEM_ID
WHERE d.ORDER_ID IN (
    SELECT h.ORDER_ID FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_HEADER h
    JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.TRUCK t ON t.TRUCK_ID = h.TRUCK_ID
    WHERE YEAR(h.ORDER_TS) = 2022 AND UPPER(t.COUNTRY) LIKE '%STATES%')
  AND d.PRICE > (SELECT AVG(d2.PRICE) FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL d2
                 WHERE d2.MENU_ITEM_ID = d.MENU_ITEM_ID)
GROUP BY 1 ORDER BY 2 DESC LIMIT 10;

-- 9. Window functions with no PARTITION BY (everything sorted on one node), over a join that multiplies rows, plus DISTINCT
SELECT ORDER_ID, ORDER_TOTAL, pct_rank, ntile_bucket, running_total
FROM (
  SELECT DISTINCT h.ORDER_ID, h.ORDER_TOTAL,
         PERCENT_RANK() OVER (ORDER BY h.ORDER_TOTAL) pct_rank,
         NTILE(100) OVER (ORDER BY h.ORDER_TOTAL) ntile_bucket,
         SUM(h.ORDER_TOTAL) OVER (ORDER BY h.ORDER_TS ROWS UNBOUNDED PRECEDING) running_total,
         COUNT(d.ORDER_DETAIL_ID) OVER (PARTITION BY h.ORDER_ID) line_cnt
  FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_HEADER h
  LEFT JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL d ON d.ORDER_ID = h.ORDER_ID
)
QUALIFY ROW_NUMBER() OVER (ORDER BY pct_rank DESC) <= 10;

-- 10. Self-join on a non-key column (row explosion) + more joins + correlated, IN and EXISTS subqueries; returns at most 10 rows
SELECT f.FRANCHISE_ID, COUNT(*) pair_cnt
FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_HEADER a
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_HEADER b
  ON a.TRUCK_ID = b.TRUCK_ID AND a.ORDER_ID <> b.ORDER_ID
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.TRUCK t ON t.TRUCK_ID = a.TRUCK_ID
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.FRANCHISE f ON f.FRANCHISE_ID = t.FRANCHISE_ID
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.LOCATION l ON l.LOCATION_ID = b.LOCATION_ID
WHERE a.ORDER_TOTAL > (SELECT AVG(h2.ORDER_TOTAL) FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_HEADER h2
                       WHERE h2.TRUCK_ID = a.TRUCK_ID)
  AND b.ORDER_ID IN (SELECT d.ORDER_ID FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL d
                     JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.MENU m ON m.MENU_ITEM_ID = d.MENU_ITEM_ID
                     WHERE UPPER(m.ITEM_CATEGORY) LIKE '%MAIN%')
  AND EXISTS (SELECT 1 FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL d2
              WHERE d2.ORDER_ID = a.ORDER_ID AND d2.QUANTITY > 1)
  AND l.CITY IN (SELECT DISTINCT CITY FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.COUNTRY WHERE CITY_POPULATION > 1000000)
GROUP BY f.FRANCHISE_ID
ORDER BY pair_cnt DESC
LIMIT 10;