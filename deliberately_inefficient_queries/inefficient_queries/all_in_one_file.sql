-- 50 deliberately inefficient queries on SNOWFLAKE_SAMPLE_DATA.
-- Every query returns <= 100 rows: heavy work runs server-side, final result is
-- aggregated or ORDER BY ... LIMIT 100 (ORDER BY forces the full computation).

-- 1. Full scan + DISTINCT on all columns, then count
SELECT COUNT(*) FROM (SELECT DISTINCT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM);

-- 2. Function on filter column (no pruning) inside CTE
WITH o AS (SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS WHERE YEAR(O_ORDERDATE) = 1995)
SELECT O_ORDERPRIORITY, COUNT(*), SUM(O_TOTALPRICE) FROM o GROUP BY 1 ORDER BY 1;

-- 3. Leading-wildcard LIKE + window rank, top 100
SELECT * FROM (
  SELECT C_CUSTKEY, C_NAME, C_ACCTBAL, RANK() OVER (ORDER BY C_ACCTBAL DESC) r
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER WHERE C_NAME LIKE '%12%')
WHERE r <= 100 ORDER BY r LIMIT 100;

-- 4. Cartesian product, aggregated
SELECT r.R_NAME, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION n,
  SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER s, SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION r
GROUP BY 1;

-- 5. Correlated scalar subquery per order, top 100
SELECT * FROM (
  SELECT O_ORDERKEY, (SELECT SUM(L_EXTENDEDPRICE) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM l
                      WHERE l.L_ORDERKEY = o.O_ORDERKEY) total
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS o)
ORDER BY total DESC LIMIT 100;

-- 6. Global sort on a text column, only 100 returned
SELECT L_ORDERKEY, L_COMMENT FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM ORDER BY L_COMMENT DESC LIMIT 100;

-- 7. UNION (dedupe) of two big key sets, counted
SELECT COUNT(*) FROM (
  SELECT L_ORDERKEY k FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM
  UNION SELECT O_ORDERKEY FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS);

-- 8. OR in join condition (blocks hash join)
SELECT C.C_MKTSEGMENT, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER C
  ON O.O_CUSTKEY = C.C_CUSTKEY OR O.O_TOTALPRICE < C.C_ACCTBAL / 100
GROUP BY 1;

-- 9. Non-equi self join, aggregated per date
SELECT A.O_ORDERDATE, COUNT(*) c FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS A
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS B
  ON A.O_ORDERDATE = B.O_ORDERDATE AND A.O_TOTALPRICE < B.O_TOTALPRICE
GROUP BY 1 ORDER BY c DESC LIMIT 100;

-- 10. Join on casted string keys
SELECT O.O_ORDERSTATUS, SUM(L.L_EXTENDEDPRICE) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM L
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS O ON TO_VARCHAR(L.L_ORDERKEY) = TO_VARCHAR(O.O_ORDERKEY)
GROUP BY 1;

-- 11. NOT IN against large subquery, aggregated
SELECT C_MKTSEGMENT, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER
WHERE C_CUSTKEY NOT IN (SELECT O_CUSTKEY FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS)
GROUP BY 1;

-- 12. Repeated scalar subqueries over the same table
SELECT (SELECT AVG(L_QUANTITY) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM) a,
       (SELECT MAX(L_QUANTITY) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM) b,
       (SELECT MIN(L_DISCOUNT) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM) c,
       (SELECT SUM(L_TAX)      FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM) d;

-- 13. COUNT DISTINCT on high-cardinality text
SELECT L_SHIPMODE, COUNT(DISTINCT L_COMMENT) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM GROUP BY 1;

-- 14. GROUP BY text column, top 100 groups
SELECT L_COMMENT, COUNT(*) c FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM
GROUP BY 1 ORDER BY c DESC, L_COMMENT LIMIT 100;

-- 15. Unpartitioned window over whole table
SELECT * FROM (
  SELECT L_ORDERKEY, L_EXTENDEDPRICE, ROW_NUMBER() OVER (ORDER BY L_EXTENDEDPRICE DESC, L_ORDERKEY) rn
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM)
WHERE rn <= 100;

-- 16. Filter applied after window instead of before
SELECT * FROM (
  SELECT L_ORDERKEY, L_SUPPKEY, L_SHIPDATE,
         RANK() OVER (PARTITION BY L_SUPPKEY ORDER BY L_EXTENDEDPRICE) r
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM)
WHERE L_SHIPDATE = '1995-01-01' ORDER BY r, L_ORDERKEY LIMIT 100;

-- 17. Wide join in CTE, filter later
WITH j AS (SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM L
           JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS O ON L.L_ORDERKEY = O.O_ORDERKEY)
SELECT O_ORDERPRIORITY, L_SHIPMODE, AVG(L_EXTENDEDPRICE) FROM j
WHERE O_ORDERSTATUS = 'F' GROUP BY 1, 2 ORDER BY 1, 2;

-- 18. TO_CHAR on date in filter
SELECT L_RETURNFLAG, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM
WHERE TO_CHAR(L_SHIPDATE, 'YYYY-MM') = '1996-03' GROUP BY 1;

-- 19. DATEADD on column instead of constant
SELECT L_LINESTATUS, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM
WHERE DATEADD(day, 30, L_SHIPDATE) > '1997-01-01' GROUP BY 1;

-- 20. Running total via self join instead of window
SELECT A.O_CUSTKEY, A.O_ORDERKEY, SUM(B.O_TOTALPRICE) running
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS A
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS B
  ON A.O_CUSTKEY = B.O_CUSTKEY AND B.O_ORDERKEY <= A.O_ORDERKEY
GROUP BY 1, 2 ORDER BY running DESC LIMIT 100;

-- 21. Row-exploding many-to-many join before aggregation
SELECT P.P_BRAND, COUNT(*) c FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART P
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PARTSUPP PS ON P.P_PARTKEY = PS.PS_PARTKEY
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L ON L.L_PARTKEY = P.P_PARTKEY
GROUP BY 1 ORDER BY c DESC LIMIT 100;

-- 22. Regex on large text column
SELECT L_SHIPMODE, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM
WHERE REGEXP_LIKE(L_COMMENT, '.*(quick|slow).*(furious|careful).*') GROUP BY 1;

-- 23. IN with DISTINCT subquery
SELECT O_ORDERPRIORITY, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS
WHERE O_ORDERKEY IN (SELECT DISTINCT L_ORDERKEY FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM WHERE L_QUANTITY > 1)
GROUP BY 1;

-- 24. Useless ORDER BY inside subquery
SELECT COUNT(*), MAX(L_COMMENT) FROM (
  SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM ORDER BY L_SHIPDATE, L_COMMENT);

-- 25. LISTAGG over big groups, keep only length
SELECT L_SUPPKEY, LENGTH(LISTAGG(L_COMMENT, ',')) len
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM GROUP BY 1 ORDER BY len DESC LIMIT 100;

-- 26. ARRAY_AGG of whole rows, keep only array size
SELECT O_CUSTKEY, ARRAY_SIZE(ARRAY_AGG(OBJECT_CONSTRUCT(*))) n
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS GROUP BY 1 ORDER BY n DESC, O_CUSTKEY LIMIT 100;

-- 27. Correlated AVG subquery per row
SELECT L_PARTKEY, COUNT(*) c FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L
WHERE L_EXTENDEDPRICE > (SELECT AVG(L2.L_EXTENDEDPRICE) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L2
                         WHERE L2.L_PARTKEY = L.L_PARTKEY)
GROUP BY 1 ORDER BY c DESC LIMIT 100;

-- 28. EXISTS with non-equi correlation
SELECT O_ORDERSTATUS, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O
WHERE EXISTS (SELECT 1 FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L
              WHERE L.L_ORDERKEY = O.O_ORDERKEY AND L.L_EXTENDEDPRICE > O.O_TOTALPRICE / 2)
GROUP BY 1;

-- 29. TPC-DS fact + dims, function filter on date
SELECT I.I_CATEGORY, SUM(SS.SS_NET_PAID) s
FROM SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.STORE_SALES SS
JOIN SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.DATE_DIM D ON SS.SS_SOLD_DATE_SK = D.D_DATE_SK
JOIN SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.ITEM I ON SS.SS_ITEM_SK = I.I_ITEM_SK
WHERE TO_CHAR(D.D_DATE, 'YYYY-MM') = '2001-12'
GROUP BY 1 ORDER BY s DESC LIMIT 100;

-- 30. Multiple COUNT DISTINCT on a big fact (one month)
SELECT COUNT(DISTINCT SS_CUSTOMER_SK), COUNT(DISTINCT SS_ITEM_SK), COUNT(DISTINCT SS_TICKET_NUMBER)
FROM SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.STORE_SALES
WHERE SS_SOLD_DATE_SK IN (SELECT D_DATE_SK FROM SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.DATE_DIM
                          WHERE D_YEAR = 2001 AND D_MOY = 12);

-- 31. Join on COALESCE keys
SELECT C.C_BIRTH_COUNTRY, COUNT(*) c FROM SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.STORE_RETURNS SR
JOIN SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.CUSTOMER C
  ON COALESCE(SR.SR_CUSTOMER_SK, -1) = COALESCE(C.C_CUSTOMER_SK, -1)
GROUP BY 1 ORDER BY c DESC LIMIT 100;

-- 32. CASE in join condition
SELECT C.C_NATIONKEY, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER C
  ON C.C_CUSTKEY = CASE WHEN O.O_ORDERSTATUS = 'F' THEN O.O_CUSTKEY ELSE O.O_CUSTKEY + 0 END
GROUP BY 1 ORDER BY 1;

-- 33. Same table scanned 3 times via UNION
SELECT 'A' f, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM WHERE L_RETURNFLAG = 'A'
UNION SELECT 'N', COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM WHERE L_RETURNFLAG = 'N'
UNION SELECT 'R', COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM WHERE L_RETURNFLAG = 'R';

-- 34. Deeply nested SELECT * subqueries
SELECT L_SHIPMODE, COUNT(*) FROM (SELECT * FROM (SELECT * FROM (
  SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM) a) b) c
WHERE L_LINENUMBER = 1 GROUP BY 1;

-- 35. HAVING instead of WHERE
SELECT L_SHIPMODE, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM
GROUP BY L_SHIPMODE HAVING L_SHIPMODE = 'AIR';

-- 36. GENERATOR cross join inflation
SELECT O_ORDERSTATUS, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS,
  TABLE(GENERATOR(ROWCOUNT => 50)) GROUP BY 1;

-- 37. Exact MEDIAN / PERCENTILE per group
SELECT L_SHIPMODE, MEDIAN(L_EXTENDEDPRICE),
       PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY L_EXTENDEDPRICE)
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM GROUP BY 1;

-- 38. Concatenated string join key
SELECT L.L_SHIPMODE, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PARTSUPP PS
JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L
  ON PS.PS_PARTKEY || '-' || PS.PS_SUPPKEY = L.L_PARTKEY || '-' || L.L_SUPPKEY
GROUP BY 1;

-- 39. Many windows with different partitions (multiple sorts)
WITH w AS (
  SELECT L_ORDERKEY,
    SUM(L_QUANTITY)      OVER (PARTITION BY L_PARTKEY)  sq,
    AVG(L_DISCOUNT)      OVER (PARTITION BY L_SUPPKEY)  ad,
    MAX(L_TAX)           OVER (PARTITION BY L_SHIPDATE) mt,
    LAG(L_EXTENDEDPRICE) OVER (PARTITION BY L_SHIPMODE ORDER BY L_COMMENT) lp
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM)
SELECT * FROM w ORDER BY sq DESC, L_ORDERKEY LIMIT 100;

-- 40. OR across columns (poor pruning)
SELECT L_SHIPMODE, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM
WHERE L_SHIPDATE = '1995-06-01' OR L_QUANTITY = 7 OR L_COMMENT LIKE '%pending%'
GROUP BY 1;

-- 41. JSON round-trip on every row
SELECT LEFT(PARSE_JSON(TO_JSON(OBJECT_CONSTRUCT(*))):L_COMMENT::STRING, 1) c, COUNT(*)
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM GROUP BY 1 ORDER BY 1 LIMIT 100;

-- 42. ORDER BY RANDOM() over full table
SELECT O_ORDERKEY, O_TOTALPRICE FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS ORDER BY RANDOM() LIMIT 100;

-- 43. Nested IN subqueries 4 levels deep
SELECT L_SHIPMODE, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM
WHERE L_ORDERKEY IN (SELECT O_ORDERKEY FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS
  WHERE O_CUSTKEY IN (SELECT C_CUSTKEY FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER
    WHERE C_NATIONKEY IN (SELECT N_NATIONKEY FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION
      WHERE N_REGIONKEY IN (SELECT R_REGIONKEY FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION WHERE R_NAME LIKE '%A%'))))
GROUP BY 1;

-- 44. Duplicate derived tables instead of one CTE
SELECT A.L_SUPPKEY, A.REV, COUNT(*) beaten
FROM (SELECT L_SUPPKEY, SUM(L_EXTENDEDPRICE) REV FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM GROUP BY 1) A
JOIN (SELECT L_SUPPKEY, SUM(L_EXTENDEDPRICE) REV FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM GROUP BY 1) B
  ON A.REV > B.REV
GROUP BY 1, 2 ORDER BY beaten DESC LIMIT 100;

-- 45. Correlated group-average with function in correlation
SELECT O_ORDERPRIORITY, COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O1
WHERE O1.O_TOTALPRICE > (SELECT AVG(O2.O_TOTALPRICE) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O2
                         WHERE O2.O_ORDERPRIORITY = O1.O_ORDERPRIORITY
                           AND YEAR(O2.O_ORDERDATE) = YEAR(O1.O_ORDERDATE))
GROUP BY 1;

-- 46. Top-3 per customer via correlated COUNT (instead of QUALIFY)
SELECT COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O1
WHERE (SELECT COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O2
       WHERE O2.O_CUSTKEY = O1.O_CUSTKEY AND O2.O_TOTALPRICE > O1.O_TOTALPRICE) < 3;

-- 47. Chained CTEs each re-scanning and re-windowing the base table
WITH base AS (SELECT * FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM),
r1 AS (SELECT b.*, DENSE_RANK() OVER (PARTITION BY L_SUPPKEY ORDER BY L_EXTENDEDPRICE DESC) dr FROM base b),
r2 AS (SELECT r1.*, NTILE(10) OVER (PARTITION BY L_SHIPMODE ORDER BY L_QUANTITY) nt FROM r1),
r3 AS (SELECT r2.*, AVG(L_DISCOUNT) OVER (PARTITION BY nt, dr) ad FROM r2)
SELECT nt, MIN(dr), MAX(ad), COUNT(*) FROM r3 GROUP BY nt ORDER BY nt;

-- 48. Subqueries in SELECT, WHERE and HAVING together
SELECT L_SHIPMODE,
  (SELECT COUNT(DISTINCT L_ORDERKEY) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM) total_orders,
  SUM(L_EXTENDEDPRICE) rev
FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM
WHERE L_SUPPKEY IN (SELECT S_SUPPKEY FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.SUPPLIER WHERE S_ACCTBAL > 0)
GROUP BY L_SHIPMODE
HAVING SUM(L_EXTENDEDPRICE) > (SELECT AVG(L_EXTENDEDPRICE) * 1000 FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM);

-- 49. TPC-DS correlated subquery against fact table
SELECT I.I_ITEM_ID, I.I_CURRENT_PRICE FROM SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.ITEM I
WHERE I.I_CURRENT_PRICE > (SELECT AVG(CR.CR_RETURN_AMOUNT) * 1.5
                           FROM SNOWFLAKE_SAMPLE_DATA.TPCDS_SF10TCL.CATALOG_RETURNS CR
                           WHERE CR.CR_ITEM_SK = I.I_ITEM_SK)
ORDER BY I.I_CURRENT_PRICE DESC LIMIT 100;

-- 50. Everything combined: CTE + correlated subquery + window + function filters + DISTINCT
WITH o AS (
  SELECT DISTINCT O.*,
    (SELECT COUNT(*) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L WHERE L.L_ORDERKEY = O.O_ORDERKEY) cnt
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O
  WHERE UPPER(O.O_COMMENT) LIKE '%SPECIAL%' AND YEAR(O.O_ORDERDATE) BETWEEN 1993 AND 1997),
ranked AS (
  SELECT o.*, ROW_NUMBER() OVER (PARTITION BY O_CUSTKEY ORDER BY cnt DESC, O_COMMENT) rn,
         SUM(O_TOTALPRICE) OVER (PARTITION BY O_CUSTKEY) cust_total
  FROM o)
SELECT O_CUSTKEY, O_ORDERKEY, cnt, cust_total FROM ranked
WHERE rn = 1 ORDER BY cust_total DESC LIMIT 100;
