-- 4. "Bought together" self-join on ORDER_DETAIL (item pairs), OR + ILIKE filter, COUNT(DISTINCT), RANK across all groups
SELECT a.MENU_ITEM_ID item_a, b.MENU_ITEM_ID item_b, COUNT(DISTINCT a.ORDER_ID) together,
       RANK() OVER (ORDER BY COUNT(DISTINCT a.ORDER_ID) DESC) rnk
FROM FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL a
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_DETAIL b
  ON a.ORDER_ID = b.ORDER_ID AND a.MENU_ITEM_ID < b.MENU_ITEM_ID
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.ORDER_HEADER h ON h.ORDER_ID = a.ORDER_ID
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.MENU ma ON ma.MENU_ITEM_ID = a.MENU_ITEM_ID
JOIN FROSTBYTE_TASTY_BYTES_2.RAW_POS.MENU mb ON mb.MENU_ITEM_ID = b.MENU_ITEM_ID
WHERE ma.TRUCK_BRAND_NAME <> mb.TRUCK_BRAND_NAME OR h.ORDER_CURRENCY ILIKE '%u%'
GROUP BY 1,2
QUALIFY rnk <= 10;

-- 5. DISTINCT over a 3-table join with OR and LIKE '%...', returns 10 rows
